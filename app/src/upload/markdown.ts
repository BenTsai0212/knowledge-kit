// Markdown：只去掉語法符號，留下純文字；不轉 HTML（上傳內容一律以純文字顯示）。
export function stripMarkdown(text: string): string {
  // 以行首為錨點的規則只用 [ \t]：\s 會連前面的換行一起吃掉，使空行消失
  return (
    text
      .replace(/\r\n?/g, "\n")
      // 程式碼區塊的 fence 行（保留內容）
      .replace(/^[ \t]*(```|~~~).*$/gm, "")
      // 圖片整個去掉；連結只留文字
      .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
      .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
      // 標題、引用、清單符號
      .replace(/^[ \t]{0,3}#{1,6}[ \t]+/gm, "")
      .replace(/^[ \t]{0,3}>[ \t]?/gm, "")
      .replace(/^[ \t]*(?:[-*+]|\d+[.)])[ \t]+/gm, "")
      // 分隔線
      .replace(/^[ \t]*([-*_])([ \t]*\1){2,}[ \t]*$/gm, "")
      // 強調與行內程式碼
      .replace(/(\*\*|__)(.+?)\1/g, "$2")
      .replace(/(\*|_)(?=\S)(.+?)(?<=\S)\1/g, "$2")
      .replace(/`([^`]*)`/g, "$1")
  );
}
